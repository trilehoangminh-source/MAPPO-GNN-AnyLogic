"""Evaluate V4 checkpoint held-out seeds without optimizer or checkpoint writes."""
from __future__ import annotations

import os
os.environ['MAPPO_DISPATCH_MASK_MODE'] = 'operation_first'
import argparse
import json
import random
import sys
from pathlib import Path
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
sys.path.insert(0,str(ROOT/'scripts'))
import numpy as np
import torch
from train_B3_edgeGAT_MAPPO_v4 import VERSION, make_v4_model, v1
from thesis.mappo.gnn_routing_B3_v121 import GraphSpec
from thesis.mappo.routing_guidance_v121 import GuidedEventCollector
from thesis.mappo.gnn_audit_uoe_v2 import RoutingGraphAudit


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--checkpoint',type=Path,required=True)
    p.add_argument('--seeds',type=int,nargs='+',default=[1001,1002,1003])
    p.add_argument('--sim-seconds',type=int,default=3600)
    p.add_argument('--port',type=int,default=51725)
    p.add_argument('--device',default='cpu')
    p.add_argument('--output',type=Path,required=True)
    p.add_argument('--guide-strength',type=float,default=None,
                   help='Default: strength used at the checkpoint last training episode')
    p.add_argument('--java-exe',default=r'C:\Program Files\AnyLogic 8.9 Personal Learning Edition\jre\bin\java.exe')
    p.add_argument('--startup-timeout',type=int,default=180)
    p.add_argument('--lock-timeout',type=int,default=180)
    o=p.parse_args()
    ckpt = o.checkpoint.resolve()
    if not ckpt.is_file() or not (ckpt.parent/'run_config.json').is_file():
        p.error('Checkpoint + run_config.json required')
    c=json.loads((ckpt.parent/'run_config.json').read_text(encoding='utf-8'))
    if c.get('version') != VERSION:
        p.error('Not an EdgeGAT-V4 checkpoint')
    if not o.seeds or len(set(o.seeds))!=len(o.seeds) or o.sim_seconds<1:
        p.error('Require distinct seeds, positive simulation time')
    if set(o.seeds) & set(range(c['seed'], c['seed']+c['episodes'])):
        p.error('Evaluation seeds overlap training seeds')
    # For evaluating intermediate checkpoint, recover precise guide from metrics.
    episode_id = int(ckpt.stem.split('_')[-1]) if ckpt.stem.startswith('checkpoint_ep_') else c['episodes']
    guide = c['guide_final'] if c['guide_decay_episodes'] <= 1 else (
        c['guide_start']+(c['guide_final']-c['guide_start'])*
        min(1.0,max(0.0,(episode_id-1)/(c['guide_decay_episodes']-1))))
    if o.guide_strength is not None:
        guide = o.guide_strength
    if not 0<=guide<=20:
        p.error('guide strength out of range')
    outfile=o.output.resolve()
    if outfile.exists():
        p.error('Refusing to overwrite '+str(outfile))
    outfile.parent.mkdir(parents=True,exist_ok=True)
    args=SimpleNamespace(model=c['model_file'],port=o.port,
        sim_seconds=o.sim_seconds,max_events=c['max_events'],
        fleetsize=c['fleetsize'],max_fleetsize=c['max_fleetsize'],
        single_dispatch_policy=c['single_dispatch_policy'],
        routing_backbone='pooled',dispatch_backbone='pooled',
        stop_mask_mode=c['stop_mask_mode'],env_type='matrix',
        seed=o.seeds[0],hidden=c['hidden'],graph_layers=c['graph_layers'],
        routing_guide_strength=guide,edge_heads=c['heads'],
        gamma=c['gamma'],gae_lambda=c['gae_lambda'],clip=c['clip'],
        lr=c['lr'],epochs=c['epochs'],mini_batches=c['mini_batches'],
        device=o.device,startup_timeout=o.startup_timeout,
        lock_timeout=o.lock_timeout,java_exe=o.java_exe)
    if not Path(args.model).is_file():
        p.error('Local AnyLogic model is missing: '+args.model)
    random.seed(args.seed);np.random.seed(args.seed);torch.manual_seed(args.seed)
    env=None
    try:
        env=v1.baseline.build_env(args)
        model,spec,_=make_v4_model(env,args)
        if spec.fingerprint!=c['graph_fingerprint']:
            raise RuntimeError('Evaluation graph differs from training graph')
        model.load(str(ckpt)) # load only checkpoints generated by you
        auditor=RoutingGraphAudit(model.roles['routing'].actor,sample_limit=1024)
        collector=GuidedEventCollector(model,env,stop_mask_mode=args.stop_mask_mode,
                                        routing_guide_strength=guide)
        with outfile.open('x',encoding='utf-8') as f:
            for seed in o.seeds:
                auditor.reset()
                _,meta=collector.episode(seed=seed,train=False,max_event_steps=args.max_events)
                if GraphSpec.from_hive(env.agent_hive).fingerprint!=spec.fingerprint:
                    raise RuntimeError('Graph changed during evaluation')
                meta['gnn_graph_mapping']=auditor.report()
                meta['dijkstra_strength_eval']=guide
                f.write(json.dumps(dict(version=VERSION,evaluation=True,seed=seed,
                    checkpoint=str(ckpt),environment=meta),default=str)+'\n')
                f.flush()
                stats=meta.get('statistics',{})
                print(f'[EDGE-GAT-V4 EVAL] seed={seed} jobDone={stats.get("jobDone",0)} '
                      f'block={stats.get("block",0)} liveLock={stats.get("liveLock",0)} '
                      f'wrongTarget={stats.get("wrongTarget",0)} '
                      f'candidate_map={meta["gnn_graph_mapping"]["candidate_map_rate"]:.1%}',flush=True)
    finally:
        if env is not None:
            env.close()
    print('[EDGE-GAT-V4 EVAL] Saved:', outfile)

if __name__=='__main__':
    main()
